export function skillByLabel(label: string) {
  const key = label.trim().toLowerCase()
  const id = labelToId[key]
  if (id) return skillById(id) ?? inspectExtras.find((skill) => skill.id === id)
  return (
    skills.find((skill) => skill.name.toLowerCase() === key) ??
    inspectExtras.find((skill) => skill.name.toLowerCase() === key)
  )
}
